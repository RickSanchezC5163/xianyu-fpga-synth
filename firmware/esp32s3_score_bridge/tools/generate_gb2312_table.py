"""Generate the offline display codec from Python's standard GB2312 mapping."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
pairs = []
for cp in range(0x80, 0x10000):
    try:
        raw = chr(cp).encode("gb2312")
    except UnicodeEncodeError:
        continue
    if len(raw) == 2:
        pairs.append((cp, int.from_bytes(raw, "big")))
lines = ["/* Generated by tools/generate_gb2312_table.py; Unicode->GB2312, sorted. */",
         "static const uint32_t gb2312_table[] = {"]
for start in range(0, len(pairs), 8):
    lines.append("    " + ",".join(f"0x{gb:04x}{cp:04x}u" for cp, gb in pairs[start:start+8]) + ",")
lines += ["};", ""]
(root / "main/gb2312_table.inc").write_text("\n".join(lines), encoding="ascii")
print(f"Generated {len(pairs)} mappings, {len(pairs)*4} Flash bytes")
